#!/usr/bin/env python3
"""Build declarative edits.json for E-M1 Mark II SD Looks Loader.

Hooks the HLS event loop at 0x602f7bf7 (every received event; half-press gate) to load LOOKS.BIN from
SD card (Slot 1: C:\EM1MOD\LOOKS.BIN, Slot 2: D:\EM1MOD\LOOKS.BIN) into
heap memory on the first post-boot shutter press.
"""
import json
import struct
import subprocess
import tempfile
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools'))

TC = Path('/home/hertzel/ep7fw-toolchains/mn10300/bin')
AS = TC / 'mn10300-elf-as'
LD = TC / 'mn10300-elf-ld'
OBJCOPY = TC / 'mn10300-elf-objcopy'
NM = TC / 'mn10300-elf-nm'
OBJDUMP = TC / 'mn10300-elf-objdump'

STOCK_BIN = ROOT / 'em1mk2' / 'firmware' / 'E1259999.BIN'
DECODED_BIN = ROOT / 'em1mk2' / 'extracted' / '00_0100_40560020.decoded.bin'
BASE = 0x60021020

CAVE_ADDR = 0x60580200
# Section 2 = 0x602ae000..0x60580800 (descriptor table 0x60027450, end getter 0x60042b35); FF tail from 0x6058018c.
S2_FF_START, S2_LOAD_END = 0x6058018c, 0x60580800
# v0.4c15: HLS event loop (0x602f7b11), every received event; was 0x6023d0db (never reached on a half-press, camera C0.0)
HOOK_ADDR = 0x602f7bf7
HOOK_STOCK_HEX = '5834fcec00000002'  # mov (52,sp),d0; btst 0x02000000,d0 = 8 bytes

SYMBOLS = {
    'em1_malloc': 0x600231fe,
    'em1_free': 0x6002323d,
    'em1_malloc_unc': 0x6002329a,   # uncached pools (P): read by the image pipeline
    'em1_free_unc': 0x600232d9,   # free for malloc 0x600231fe (0x600232d9 frees the uncached pool)
    'em1_fopen': 0x6062ce6a,
    'em1_fclose': 0x6062ce73,
    'em1_fread': 0x6062cff9,
    'em1_fseek': 0x6062d0f1,
    'em1_ftell': 0x6062d087,
    'em1_ev_ret': 0x602f7bff,       # after the replaced btst (beq 0x602f7c12)
    'em1_getter': 0x6005e6cf,       # property getter (d0 key, d1 index, a0 0), [d2,d3],12
    'em1_sel_color': 0x603ec8a2,    # COLOR selector: add 1816,a3 ... call builder 0x603ec642
    'em1_sel_other': 0x603ec8d3,    # COLOR selector: stock non-11 path
    'em1_hl_resume': 0x603ec8be,    # after the builder: beq 0x603ec912 (flags from the replayed btst)
}

# Colour-stage hooks (E-P7 0x603b02c1 / 0x603b02de equivalents), with their stock bytes.
COLOUR_HOOKS = [
    # (site, stock hex, symbol, pad)  stock: cmp 11,d1; bne 0x603ec8d3; mov (12,a2),d1
    (0x603ec89b, 'a50bc936f8060c', 'cc_sel', 2),
    # stock: mov (60,a2),d0; btst 2,d0
    (0x603ec8b8, 'f8023cf8ec02', 'cc_hl', 1),
]


def write_hl_luts(path):
    """hl_luts.inc from the E-P7 bundles constants (patches/bundles/build.py: HUE_LUT_X, L_LUT_X, PERM)."""
    import importlib.util
    spec = importlib.util.spec_from_file_location('ep7_bundles', ROOT / 'patches' / 'bundles' / 'build.py')
    bb = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(bb)
    assert len(bb.HUE_LUT_X) == 31 and len(bb.L_LUT_X) == 31 and bb.OUT_RECORDS == 688
    lines = ['/* generated by sd_loader/build.py from patches/bundles/build.py (E-P7 extended H/L) */',
             '.balign 2', 'hl_hue_lut:', '    .hword ' + ','.join(str(v) for v in bb.HUE_LUT_X),
             'hl_light_lut:', '    .hword ' + ','.join(str(v) for v in bb.L_LUT_X),
             'hl_perm:', '    .byte ' + ','.join(str(v) for v in bb.PERM), '.balign 4', '']
    path.write_text('\n'.join(lines))


def get_main_payload() -> bytes:
    if DECODED_BIN.exists():
        return DECODED_BIN.read_bytes()
    try:
        import oly_container as oc
    except ImportError:
        sys.path.insert(0, str(ROOT))
        import caduceus as oc
    blocks = oc.parse(STOCK_BIN.read_bytes())
    b100 = [b for b in blocks if b.kind == 0x100][0]
    return b100.payload


def build():
    # 1. Assemble sd_loader.s
    src = Path(__file__).parent / 'sd_loader.s'
    write_hl_luts(Path(__file__).parent / 'hl_luts.inc')
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp = Path(tmpdir)
        obj = tmp / 'loader.o'
        elf = tmp / 'loader.elf'
        bin_out = tmp / 'loader.bin'

        subprocess.run([AS, '-I', str(Path(__file__).parent.parent), '-I', str(Path(__file__).parent), '-o', str(obj), str(src)], check=True)

        ld_cmd = [LD, '-Ttext', f'{CAVE_ADDR:#x}', '-e', '_start']
        for k, v in SYMBOLS.items():
            ld_cmd.append(f'--defsym={k}={v:#x}')
        ld_cmd.extend(['-o', str(elf), str(obj)])
        subprocess.run(ld_cmd, check=True)

        subprocess.run([OBJCOPY, '-O', 'binary', '-j', '.text', str(elf), str(bin_out)], check=True)
        cave_payload = bin_out.read_bytes()

        # Export the shared-state entry points for color_creator_wheel (Section 6 may call
        # Section 2 code: load order 1, 7, 2, 3, 4, 5, 6).
        nm_out = subprocess.check_output([NM, str(elf)]).decode()
        exports = {}
        for line in nm_out.splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[2] in ('p_get', 'p_ensure', 'cc_sel', 'cc_hl', 'look_fill'):
                exports[parts[2]] = int(parts[0], 16)
        assert set(exports) == {'p_get', 'p_ensure', 'cc_sel', 'cc_hl', 'look_fill'}, exports
        (Path(__file__).parent / 'exports.json').write_text(
            json.dumps({k: f'{v:#x}' for k, v in exports.items()}, indent=2) + '\n')

        # 2. Assemble hook at HOOK_ADDR (jmp sd_loader_entry)
        hook_src = tmp / 'hook.s'
        hook_obj = tmp / 'hook.o'
        hook_elf = tmp / 'hook.elf'
        hook_bin = tmp / 'hook.bin'

        hook_src.write_text("""
.am33_2
.text
.global _start
_start:
jmp sd_loader_entry
nop
nop
nop
""")
        subprocess.run([AS, '-o', str(hook_obj), str(hook_src)], check=True)
        subprocess.run([
            LD, '-Ttext', f'{HOOK_ADDR:#x}',
            f'--defsym=sd_loader_entry={CAVE_ADDR:#x}',
            '-o', str(hook_elf), str(hook_obj)
        ], check=True)
        subprocess.run([OBJCOPY, '-O', 'binary', '-j', '.text', str(hook_elf), str(hook_bin)], check=True)
        hook_payload = hook_bin.read_bytes()

    assert len(hook_payload) == 8, f"Hook payload length must be 8, got {len(hook_payload)}"

    # 3. Verify against stock binary
    main = get_main_payload()

    # Cave inside the bytes Section 2 really loads, with 16-byte guards
    assert CAVE_ADDR >= S2_FF_START + 16 and CAVE_ADDR + len(cave_payload) <= S2_LOAD_END - 16, 'cave outside Section 2 load'

    # Verify cave is all 0xFF
    cave_off = CAVE_ADDR - BASE
    cave_stock = main[cave_off:cave_off + len(cave_payload)]
    assert all(b == 0xFF for b in cave_stock), "Target cave contains non-0xFF bytes!"

    # Verify hook site stock bytes
    hook_off = HOOK_ADDR - BASE
    assert main[hook_off:hook_off + 8].hex() == HOOK_STOCK_HEX, "Hook site mismatch!"

    # 4. Generate edits.json
    edits = {
        "components": ["0x100"],
        "edits": [
            {
                "kind": "0x100",
                "addr": f"{CAVE_ADDR:#x}",
                "expect": "ff" * len(cave_payload),
                "new": cave_payload.hex(),
                "why": f"SD Custom Looks Loader cave routine ({len(cave_payload)} bytes)"
            },
            {
                "kind": "0x100",
                "addr": f"{HOOK_ADDR:#x}",
                "expect": HOOK_STOCK_HEX,
                "new": hook_payload.hex(),
                "why": "Hook HLS event loop (half-press) to load LOOKS.BIN from SD card"
            }
        ]
    }

    for site, stock_hex, sym, pad in COLOUR_HOOKS:
        off = site - BASE
        assert main[off:off + len(stock_hex) // 2].hex() == stock_hex, f'stock mismatch at {site:#x}'
        disp = exports[sym] - site
        new = b'\xdc' + struct.pack('<i', disp) + b'\xcb' * pad     # jmp d32; nop
        assert len(new) == len(stock_hex) // 2
        edits['edits'].append({'kind': '0x100', 'addr': f'{site:#x}', 'expect': stock_hex, 'new': new.hex(),
                               'why': f'COLOR selector hook -> {sym} (E-P7 colour engine for Color Creator looks)'})

    out_file = Path(__file__).parent / 'edits.json'
    out_file.write_text(json.dumps(edits, indent=2) + '\n')
    print(f'Generated {out_file} ({len(cave_payload)} bytes cave routine, 8 bytes hook)')


if __name__ == '__main__':
    build()
